/**
 * export_lessons.ts — generates `apps-script/LessonsData.gs` from course content.
 *
 * The Apps Script backend (Code.gs) uses COURSE_DATA to:
 *  - seed the "Lessons" worksheet (no manual rows — spec §18B "derived"),
 *  - validate lessonId / vocabularyId on EVERY write (server never trusts
 *    client-supplied IDs — docs/PHASE2_INTEGRATION.md §7),
 *  - recompute TotalVocabularyCount / CompletedVocabularyCount /
 *    CompletionPercentage server-side (spec §18D).
 *
 * Run:  npm run lessons:export     (after any lesson-content change)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { course, getAllLessons } from '../src/content/course';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const lessons = getAllLessons()
  .slice()
  .sort((a, b) => a.order - b.order)
  .map((l) => ({
    id: l.id,
    order: l.order,
    titleEn: l.title.en,
    titleZh: l.title.zh,
    vocabIds: l.vocabulary.map((v) => v.id),
  }));

const data = {
  courseId: course.id,
  courseLevel: course.level,
  totalLessons: course.totalLessons,
  generatedAt: new Date().toISOString(),
  lessons,
};

const body = `// AUTO-GENERATED by \`npm run lessons:export\` — DO NOT EDIT BY HAND.
// Source of truth: src/content/course.ts + lesson files. Re-run after content changes
// and re-paste this file into the Apps Script project (see docs/DEPLOY_PHASE2_AR.md).
var COURSE_DATA = ${JSON.stringify(data, null, 2)};
`;

const outDir = join(root, 'apps-script');
mkdirSync(outDir, { recursive: true });
const out = join(outDir, 'LessonsData.gs');
writeFileSync(out, body, 'utf8');

const vocabTotal = lessons.reduce((s, l) => s + l.vocabIds.length, 0);
console.log(`Wrote apps-script/LessonsData.gs — ${lessons.length} lessons, ${vocabTotal} vocabulary ids.`);
