/**
 * export_audio_manifest — walks all course content and produces:
 *
 *   1. audio-manifest.json
 *        The full list of speakable clips: { id, text, voice }.
 *        Consumed by scripts/generate_audio.py (edge-tts).
 *
 *   2. src/services/audioManifest.generated.ts
 *        The runtime lookup (clipId -> URL) for the app. Only clips whose
 *        mp3 file actually exists in src/assets/audio are imported, so the
 *        build never breaks on not-yet-generated audio. Re-run this after
 *        generating audio.
 *
 * Clip IDs == stable content IDs (spec §20), so audio survives UI redesigns.
 * Audio is deduplicated by ID: the same sentence reused as a grammar example
 * is generated once.
 *
 * Usage: npm run audio:manifest
 */
import { readdirSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getAllLessons } from '../src/content/course';
import type { VoiceHint } from '../src/types/content';

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(here, '..');
const audioDir = join(projectRoot, 'src', 'assets', 'audio');
const manifestPath = join(projectRoot, 'audio-manifest.json');
const generatedPath = join(projectRoot, 'src', 'services', 'audioManifest.generated.ts');

interface Clip {
  id: string;
  text: string;
  voice: VoiceHint;
}

function collectClips(): Clip[] {
  const clips = new Map<string, Clip>(); // dedupe by clip id
  const add = (id: string, text: string, voice: VoiceHint = 'female'): void => {
    const trimmed = text.trim();
    if (!trimmed) return;
    if (!clips.has(id)) clips.set(id, { id, text: trimmed, voice });
  };

  for (const lesson of getAllLessons()) {
    for (const word of lesson.vocabulary) {
      add(word.id, word.hanzi);
      for (const ex of word.examples ?? []) add(ex.id, ex.audioText ?? ex.hanzi);
    }
    for (const s of lesson.sentences) add(s.id, s.audioText ?? s.hanzi);
    for (const g of lesson.grammar) {
      for (const ex of g.examples ?? []) add(ex.id, ex.audioText ?? ex.hanzi);
    }
    for (const conv of lesson.conversations) {
      const speakerVoice = new Map(conv.speakers.map((s) => [s.id, s.voice ?? ('female' as VoiceHint)]));
      for (const line of conv.lines) {
        add(line.id, line.hanzi, speakerVoice.get(line.speakerId) ?? 'female');
      }
    }
  }
  return [...clips.values()].sort((a, b) => a.id.localeCompare(b.id));
}

function writeGeneratedManifest(existingIds: Set<string>, allClips: Clip[], onlyPrefix?: string): void {
  const included = allClips.filter(
    (c) => existingIds.has(c.id) && (onlyPrefix ? c.id.startsWith(onlyPrefix) : true),
  );
  const lines: string[] = [
    '// AUTO-GENERATED by `npm run audio:manifest` — DO NOT EDIT BY HAND.',
    `// ${included.length} of ${allClips.length} course clips have generated audio.`,
    '// Regenerate after adding lesson content or generating audio files.',
  ];
  included.forEach((clip, i) => {
    lines.push(`import clip${i} from '../assets/audio/${clip.id}.mp3';`);
  });
  lines.push('export const audioManifest: Record<string, string> = {');
  included.forEach((clip, i) => {
    lines.push(`  '${clip.id}': clip${i},`);
  });
  lines.push('};');
  writeFileSync(generatedPath, lines.join('\n') + '\n', 'utf8');
  console.log(`[manifest] wrote ${generatedPath} (${included.length}/${allClips.length} clips available)`);
}

function main(): void {
  const clips = collectClips();
  writeFileSync(
    manifestPath,
    JSON.stringify({ generatedAt: new Date().toISOString(), clipCount: clips.length, clips }, null, 2) + '\n',
    'utf8',
  );
  console.log(`[manifest] wrote ${manifestPath} (${clips.length} clips needed)`);

  if (!existsSync(audioDir)) mkdirSync(audioDir, { recursive: true });
  const existing = new Set(
    readdirSync(audioDir)
      .filter((f) => f.endsWith('.mp3'))
      .map((f) => f.replace(/\.mp3$/, '')),
  );
  // Optional --only <prefix>: emit a runtime manifest with a subset of clips
  // (used to build small per-lesson single-file previews).
  const onlyIdx = process.argv.indexOf('--only');
  const onlyPrefix = onlyIdx !== -1 ? process.argv[onlyIdx + 1] : undefined;
  writeGeneratedManifest(existing, clips, onlyPrefix);

  const missing = clips.filter((c) => !existing.has(c.id));
  if (missing.length > 0) {
    console.log(`[manifest] ${missing.length} clip(s) still missing audio — run: python3 scripts/generate_audio.py`);
  }
}

main();
